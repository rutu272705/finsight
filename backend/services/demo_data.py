"""Clearly-labelled synthetic data for OFFLINE DEMOS ONLY (DEMO_MODE=true).

Everything produced here is fabricated: prices follow a seeded random walk and headlines come from
templates. The API marks every payload with ``"demo": true`` and the UI shows a banner, so demo output
can never be mistaken for real market data.
"""
from __future__ import annotations

import hashlib
import random
from datetime import datetime, timedelta, timezone

import numpy as np
import pandas as pd

from . import directory

_PERIOD_DAYS = {"1mo": 31, "3mo": 93, "6mo": 186, "1y": 366, "2y": 731, "5y": 1827, "max": 2500}


def _seed(symbol: str) -> int:
    return int(hashlib.md5(symbol.encode()).hexdigest()[:8], 16)


def demo_profile(symbol: str) -> dict:
    found = directory.lookup(symbol)
    currency = "INR" if symbol.endswith((".NS", ".BO")) else "GBP" if symbol.endswith(".L") else "USD"
    return {
        "symbol": symbol,
        "name": found[0] if found else f"{symbol} (demo company)",
        "exchange": found[1] if found else "DEMO",
        "currency": currency,
    }


def demo_history(symbol: str, period: str = "1y") -> pd.DataFrame:
    days = _PERIOD_DAYS.get(period, 366)
    rng = np.random.default_rng(_seed(symbol))
    end = pd.Timestamp(datetime.now().date())
    idx = pd.bdate_range(end=end, periods=int(days * 5 / 7) + 1)
    n = len(idx)
    # regime-switching drift/volatility so the series has realistic trends and clusters
    regimes = rng.choice([-0.0006, 0.0001, 0.0007], size=n // 40 + 2, p=[0.3, 0.3, 0.4])
    drift = np.repeat(regimes, 40)[:n]
    vol = np.repeat(rng.uniform(0.008, 0.022, size=n // 60 + 2), 60)[:n]
    rets = rng.normal(drift, vol)
    start = 80 + (_seed(symbol) % 1900)
    close = start * np.exp(np.cumsum(rets))
    open_ = close * (1 + rng.normal(0, 0.003, n))
    high = np.maximum(open_, close) * (1 + np.abs(rng.normal(0, 0.004, n)))
    low = np.minimum(open_, close) * (1 - np.abs(rng.normal(0, 0.004, n)))
    volume = (rng.lognormal(mean=15, sigma=0.35, size=n) * (1 + 3 * np.abs(rets) / 0.02)).astype(int)
    return pd.DataFrame({"Open": open_, "High": high, "Low": low, "Close": close, "Volume": volume}, index=idx)


_POS = [
    "{n} beats quarterly earnings estimates as revenue climbs {p}%",
    "{n} announces dividend increase after record profit",
    "Analysts upgrade {n} citing strong growth and expanding margins",
    "{n} wins major contract, shares rally on bullish outlook",
    "{n} reports surge in demand, raises full-year guidance",
]
_NEG = [
    "{n} misses revenue forecast as profit falls {p}%",
    "{n} faces regulatory probe, shares slump on investor concerns",
    "Analysts downgrade {n} amid weak demand and rising costs",
    "{n} announces layoffs after quarterly loss widens",
    "{n} cuts guidance citing inflation pressure and supply disruption",
]
_NEU = [
    "{n} to hold annual shareholder meeting next month",
    "{n} appoints new chief financial officer",
    "{n} announces schedule for upcoming earnings call",
    "{n} files routine disclosure with market regulator",
    "Interest rate decision looms as investors watch {n} and the wider market",
]
_SOURCES = ["Demo Wire", "Sample Business Daily", "Placeholder Markets", "Mock Financial Times"]


def demo_news(symbol: str, company: str, days: int = 14) -> list[dict]:
    rng = random.Random(_seed(symbol))
    now = datetime.now(timezone.utc)
    out = []
    for i in range(24):
        bucket = rng.choices([_POS, _NEG, _NEU], weights=[0.4, 0.3, 0.3])[0]
        title = rng.choice(bucket).format(n=company.split(",")[0].replace(" Limited", "").replace(" Inc.", ""), p=rng.randint(2, 18))
        published = now - timedelta(hours=rng.randint(1, days * 24))
        out.append({
            "title": title,
            "source": rng.choice(_SOURCES),
            "url": f"https://example.com/demo/{symbol}/{i}",
            "published_at": published.isoformat(timespec="seconds"),
            "description": title + ". This is synthetic demonstration text generated by FinSight demo mode; "
                           "it does not describe a real event.",
        })
    return out
